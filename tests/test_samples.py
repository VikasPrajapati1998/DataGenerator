ALL_SAMPLES = sorted((Path(__file__).resolve().parents[1] / "samples" / "schemas").glob("*.json"))
SAMPLES = [p for p in ALL_SAMPLES if '"tables"' not in p.read_text(encoding="utf-8")]  # single-table samples
MULTI_SAMPLES = [p for p in ALL_SAMPLES if p not in SAMPLES]  # tested in test_multi_table.py
_RECORDS = 400


def _placeholder_profiles(schema) -> dict[str, dict[str, ProfileRange]]:
    """Stand-in ranges for profile fields the LLM would calibrate at run time."""
    profiles = {}
    for name in schema.profile_fields:
        spec = schema.fields[name]
        if spec.profile is None:
            categories = schema.fields[spec.depends_on].allowed_values or []
            profiles[name] = {str(c): ProfileRange(min=100 + i, typical=500 + i, max=1000 + i)
                              for i, c in enumerate(categories)}
    return profiles


def test_there_are_many_samples() -> None:
    assert len(SAMPLES) >= 15


# Real-world formats whose size is fixed by convention (Indian vehicle plates, mobile numbers).
_FIXED_FORMATS = {("automobile_vehicles", "registration_no"), ("telecom_subscribers", "msisdn")}


@pytest.mark.parametrize("path", SAMPLES, ids=lambda p: p.stem)
def test_unique_patterns_scale_to_a_million_records(path: Path) -> None:
    request = GenerationRequest(**json.loads(path.read_text(encoding="utf-8")))
    schema = parse_schema(request.data_schema, request.generation_instructions)
    expected = check_unique_capacity(schema, 1_000_000)
    for name, collisions in expected.items():
        limit = 200 if (path.stem, name) in _FIXED_FORMATS else 5
        assert collisions <= limit, f"{path.name}:{name} expects {collisions:.0f} collisions at 1M records"


@pytest.mark.parametrize("path", SAMPLES, ids=lambda p: p.stem)
def test_samples_leave_runtime_settings_to_the_engine(path: Path) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    assert "batch_size" not in data, f"{path.name} hardcodes batch_size"
    if path.stem not in ("employees_mock", "customer_profiles_pool"):
        assert not {"model_provider", "model_name", "model_pool"} & set(data), f"{path.name} hardcodes models"


@pytest.mark.parametrize("path", SAMPLES, ids=lambda p: p.stem)
def test_sample_generates_valid_records(path: Path, tmp_path: Path) -> None:
    request = GenerationRequest(**json.loads(path.read_text(encoding="utf-8")))
    schema = parse_schema(request.data_schema, request.generation_instructions)
    profiles = _placeholder_profiles(schema)
    builder = RecordBuilder(schema, request.total_records, profiles)
    validator, realism = RecordValidator(schema), RealismValidator(schema, profiles)
    guards = NodeGuardrails(schema, GuardrailConfig(), validator, realism, None, None)
    faker = Faker(schema.locale)
    faker.seed_instance(1)
    records = []
    for index in range(_RECORDS):
        record = builder.build(index, random.Random(index), faker)
        for name in schema.llm_fields:  # LLM text is not generated offline; any plausible value will do
            record[name] = f"Plausible sample text number {index} for testing."
        records.append(record)
    rejected = guards.check(1, records, list(range(_RECORDS)), BatchGuardState())
    # Rare in-batch collisions of unique random values (e.g. names-based emails) are regenerated by the engine;
    # schema, rule and realism violations must not happen at all.
    hard = {pos: reason for pos, reason in rejected.items() if not reason.startswith("duplicate")}
    assert hard == {}, f"{path.name}: {list(hard.values())[:3]}"
    assert len(rejected) <= _RECORDS * 0.02, f"{path.name}: too many duplicates {list(rejected.values())[:3]}"
