"""Multi-table datasets: several related tables from one schema file, generated in dependency order.

A multi-table schema has a ``tables`` object instead of fields::

    {"tables": {
        "suppliers": {"records": 180, "schema": {...}},
        "purchase_orders": {"records": 20000,
                            "links": {"supplier": {"table": "suppliers"}},
                            "schema": {"po_no": {...}, "supplier_id": {"link": "supplier", "column": "supplier_id"}}},
        "po_lines": {"per_parent": {"table": "purchase_orders", "min": 1, "max": 5},
                     "schema": {"po_no": {"link": "parent", "column": "po_no"},
                                "line_no": {"generator": "child_index"}}}}}

Each table is generated by the normal engine (batches, split runs, mock or LLM), one after another. When a parent
table is done, the columns its children need are written to a key store (:mod:`app.generation.links`), and its
output file is exported without ``hidden`` helper columns. Every child file is then checked: each linked key
combination must exist in the parent (respecting ``where`` and ``match``), and ``primary_key`` columns must be unique.
Results go to ``final/<table>.<format>``; a ``multi_table.json`` manifest makes the run resumable.
"""

