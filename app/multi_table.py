logger = get_logger(__name__)

MANIFEST = "multi_table.json"
PARENT_LINK = "parent"
_NAME = r"[A-Za-z_][A-Za-z0-9_]{0,39}"


def is_multi_table(data_schema: Any) -> bool:
    """Whether a request's ``schema`` describes several tables."""
    return isinstance(data_schema, dict) and isinstance(data_schema.get("tables"), dict)


@dataclass
class TableSpec:
    """One parsed table of a multi-table schema."""

    name: str
    raw_schema: dict[str, Any]
    schema: DatasetSchema
    records: int | None
    per_parent: dict[str, Any] | None
    links: dict[str, dict[str, Any]]
    primary_key: list[str]
    instructions: str | None
    estimate: int = 0
    needed: set[str] = field(default_factory=set)  # columns child tables read from this table

    @property
    def parents(self) -> set[str]:
        """Tables this table reads from."""
        return {link["table"] for link in self.links.values()}

    @property
    def hidden(self) -> list[str]:
        """Helper columns left out of the output file."""
        return [n for n, s in self.schema.fields.items() if s.hidden]

    def link_fields(self, link: str) -> dict[str, str]:
        """Child field -> parent column for the ``parent`` fields of ``link``."""
        return {n: s.column for n, s in self.schema.fields.items()  # type: ignore[misc]
                if s.generator == "parent" and s.link == link}


def _check_name(kind: str, name: str) -> None:
    import re  # pylint: disable=import-outside-toplevel

    if not re.fullmatch(_NAME, name):
        raise SchemaError(f"Invalid {kind} name {name!r}: use letters, digits and underscores (max 40)")


def _raw_fields(raw: Any) -> dict[str, Any]:
    if not isinstance(raw, dict) or not raw:
        raise SchemaError("each table needs a non-empty \"schema\"")
    return raw["fields"] if isinstance(raw.get("fields"), dict) else raw


def _read_links(name: str, table: dict[str, Any], tables: dict[str, Any]) -> dict[str, dict[str, Any]]:
    links: dict[str, dict[str, Any]] = {}
    for link_name, raw in (table.get("links") or {}).items():
        _check_name("link", link_name)
        if link_name == PARENT_LINK:
            raise SchemaError(f"Table {name!r}: the link name 'parent' is reserved for per_parent tables")
        if isinstance(raw, str):
            raw = {"table": raw}
        if not isinstance(raw, dict) or raw.get("table") not in tables:
            raise SchemaError(f"Table {name!r}: link {link_name!r} must name an existing table "
                              f"(one of {sorted(tables)})")
        unknown = set(raw) - {"table", "mode", "where", "match"}
        if unknown:
            raise SchemaError(f"Table {name!r}: link {link_name!r} has unknown settings {sorted(unknown)}")
        mode = raw.get("mode", "random")
        if mode not in LINK_MODES:
            raise SchemaError(f"Table {name!r}: link {link_name!r} mode must be one of {', '.join(LINK_MODES)}")
        if raw.get("match") and mode != "random":
            raise SchemaError(f"Table {name!r}: link {link_name!r}: match only works with mode random")
        links[link_name] = {"table": raw["table"], "mode": mode, "where": dict(raw.get("where") or {}),
                            "match": dict(raw.get("match") or {})}
    per_parent = table.get("per_parent")
    if per_parent is not None:
        if not isinstance(per_parent, dict) or per_parent.get("table") not in tables:
            raise SchemaError(f"Table {name!r}: per_parent must name an existing table")
        links[PARENT_LINK] = {"table": per_parent["table"], "mode": "per_parent",
                              "where": dict(per_parent.get("where") or {}), "match": {}}
    if any(link["table"] == name for link in links.values()):
        raise SchemaError(f"Table {name!r} links to itself; use the reference generator inside one table")
    return links


def _per_parent(name: str, raw: dict[str, Any]) -> dict[str, Any]:
    low, high = int(raw.get("min", 1)), int(raw.get("max", raw.get("min", 1)))
    if low < 0 or high < low or high > 100_000:
        raise SchemaError(f"Table {name!r}: per_parent needs 0 <= min <= max <= 100000")
    weights = raw.get("weights")
    if weights is not None and (len(weights) != high - low + 1 or any(w < 0 for w in weights) or not sum(weights)):
        raise SchemaError(f"Table {name!r}: per_parent weights need one value per count from min to max")
    unknown = set(raw) - {"table", "min", "max", "weights", "where"}
    if unknown:
        raise SchemaError(f"Table {name!r}: per_parent has unknown settings {sorted(unknown)}")
    return {"table": raw["table"], "min": low, "max": high, "weights": weights, "where": dict(raw.get("where") or {})}


def parse_tables(data_schema: dict[str, Any], instructions: str | None = None) -> list[TableSpec]:
    """Validate a multi-table schema and return its tables in generation order (parents first).

    Raises:
        SchemaError: On unknown tables, links or columns, cycles, or invalid table schemas.
    """
    tables = data_schema.get("tables")
    if not isinstance(tables, dict) or not tables:
        raise SchemaError("\"tables\" must be a non-empty object of table definitions")
    extra = set(data_schema) - {"tables"}
    if extra:
        raise SchemaError(f"Unknown keys next to \"tables\": {sorted(extra)}")
    graph: dict[str, set[str]] = {}
    links: dict[str, dict[str, dict[str, Any]]] = {}
    for name, table in tables.items():
        _check_name("table", name)
        if not isinstance(table, dict) or "schema" not in table:
            raise SchemaError(f"Table {name!r} needs a \"schema\"")
        unknown = set(table) - {"schema", "records", "per_parent", "links", "primary_key", "instructions"}
        if unknown:
            raise SchemaError(f"Table {name!r} has unknown settings {sorted(unknown)}")
        if (table.get("records") is None) == (table.get("per_parent") is None):
            raise SchemaError(f"Table {name!r} needs either \"records\" (a number) or \"per_parent\"")
        links[name] = _read_links(name, table, tables)
        graph[name] = {link["table"] for link in links[name].values()}
    try:
        order = list(TopologicalSorter(graph).static_order())
    except CycleError as exc:
        raise SchemaError(f"Table links contain a cycle: {exc.args[1]}") from exc

    specs: dict[str, TableSpec] = {}
    for name in order:
        table = tables[name]
        raw_schema = json.loads(json.dumps(table["schema"]))
        fields = _raw_fields(raw_schema)
        for field_name, raw in fields.items():
            if isinstance(raw, dict) and raw.get("link") is not None:
                link = links[name].get(raw["link"])
                if link is None:
                    raise SchemaError(f"Table {name!r}, field {field_name!r}: unknown link {raw['link']!r} "
                                      f"(links: {sorted(links[name])})")
                parent = specs[link["table"]].schema
                if raw.get("column") not in parent.fields:
                    raise SchemaError(f"Table {name!r}, field {field_name!r}: table {link['table']!r} has no "
                                      f"column {raw.get('column')!r}")
                raw.setdefault("type", parent.fields[raw["column"]].type)
                raw["after"] = sorted({*raw.get("after", []), *link["match"]})
        try:
            schema = parse_schema(raw_schema, " ".join(filter(None, [instructions, table.get("instructions")])))
        except SchemaError as exc:
            raise SchemaError(f"Table {name!r}: {exc}") from exc
        for link_name, link in links[name].items():
            parent = specs[link["table"]]
            for column in link["where"]:
                if column not in parent.schema.fields:
                    raise SchemaError(f"Table {name!r}: link {link_name!r} filters on unknown column {column!r} "
                                      f"of {link['table']!r}")
            for child, column in link["match"].items():
                if child not in schema.fields or column not in parent.schema.fields:
                    raise SchemaError(f"Table {name!r}: link {link_name!r} matches {child!r} to {column!r}, but "
                                      "one of them does not exist")
        for field_name, spec in schema.fields.items():
            if spec.generator == "child_index" and PARENT_LINK not in links[name]:
                raise SchemaError(f"Table {name!r}, field {field_name!r}: child_index needs \"per_parent\"")
        primary_key = list(table.get("primary_key") or [])
        missing = [c for c in primary_key if c not in schema.fields]
        if missing:
            raise SchemaError(f"Table {name!r}: primary_key columns {missing} do not exist")
        per_parent = _per_parent(name, table["per_parent"]) if table.get("per_parent") is not None else None
        records = None
        if per_parent is None:
            try:
                records = int(table["records"])
            except (TypeError, ValueError) as exc:
                raise SchemaError(f"Table {name!r}: records must be a number") from exc
            if not 1 <= records <= 50_000_000:
                raise SchemaError(f"Table {name!r}: records must be between 1 and 50,000,000")
            estimate = records
        else:
            if per_parent["weights"]:
                weights = per_parent["weights"]
                mean = sum((per_parent["min"] + i) * w for i, w in enumerate(weights)) / sum(weights)
            else:
                mean = (per_parent["min"] + per_parent["max"]) / 2
            estimate = max(1, round(specs[per_parent["table"]].estimate * mean))
        spec = TableSpec(name=name, raw_schema=raw_schema, schema=schema, records=records, per_parent=per_parent,
                         links=links[name], primary_key=primary_key, instructions=table.get("instructions"),
                         estimate=estimate)
        for link_name, link in spec.links.items():
            parent = specs[link["table"]]
            parent.needed.update(spec.link_fields(link_name).values(), link["where"], link["match"].values())
        specs[name] = spec
    return [specs[name] for name in order]


def estimate_records(data_schema: dict[str, Any]) -> int:
    """Rough total of all tables (exact for fixed tables, the average for per-parent ones)."""
    return sum(t.estimate for t in parse_tables(data_schema))


class _Writer:
    """Writes the key store of a parent table while its rows stream past."""

    def __init__(self, path: Path, columns: list[str]) -> None:
        self.path, self.columns = path, columns
        path.parent.mkdir(parents=True, exist_ok=True)
        self.temp = Path(f"{path}.jsonl.tmp")
        self.handle = self.temp.open("wb")
        self.offsets = array("q", [0])

    def add(self, record: dict[str, Any]) -> None:
        line = json.dumps({c: record.get(c) for c in self.columns}, ensure_ascii=False).encode("utf-8")
        self.handle.write(line)
        self.offsets.append(self.offsets[-1] + len(line))

    def close(self) -> None:
        self.handle.close()
        self.temp.replace(Path(f"{self.path}.jsonl"))
        write_int64(Path(f"{self.path}.offsets"), self.offsets)


def iter_store(store: str) -> Any:
    """Rows of a key store, in order."""
    with Path(f"{store}.jsonl").open("rb") as handle:
        offsets = array("q")
        with Path(f"{store}.offsets").open("rb") as raw:
            offsets.frombytes(raw.read())
        for start, end in zip(offsets, offsets[1:]):
            handle.seek(start)
            yield json.loads(handle.read(end - start))


class MultiTableRunner:
    """Runs and resumes multi-table jobs with an existing engine."""

    def __init__(self, engine: SyntheticDataEngine) -> None:
        self.engine = engine

    # -- entry points -----------------------------------------------------------------
    def start(self, request: GenerationRequest) -> JobResult:
        """Create the run folder and manifest for ``request`` and execute it."""
        specs = parse_tables(request.data_schema, request.generation_instructions)
        schema_name = safe_name(request.schema_name or "dataset")
        run_id = request.job_id or new_job_id(schema_name)
        output_dir = (Path(request.output_dir) if request.output_dir else self.engine.settings.output_dir).resolve()
        run_dir = output_dir / f"Jobs_{time.strftime('%Y-%m-%d')}" / schema_name / run_id
        if (run_dir / MANIFEST).exists():
            raise ConfigurationError(f"Multi-table run {run_id} already exists; use resume to continue it")
        base = request.model_dump(by_alias=True)
        base.update(job_id=None, schema_name=schema_name, output_dir=None, links=None,
                    seed=request.seed if request.seed is not None else random.SystemRandom().randrange(2 ** 31))
        manifest = {
            "run_id": run_id, "schema_name": schema_name, "created_at": utc_now_iso(), "status": "running",
            "output_format": request.output_format, "request": base,
            "tables": [{"name": s.name, "status": "pending", "records": s.records, "estimate": s.estimate}
                       for s in specs],
        }
        self._save(run_dir, manifest)
        logger.info("Multi-table run %s: %d tables (%s) in %s", run_id, len(specs),
                    " -> ".join(s.name for s in specs), run_dir)
        return self._execute(run_dir, manifest)

    def resume(self, run_dir: Path) -> JobResult:
        """Continue a multi-table run; finished tables are kept."""
        manifest = read_json(run_dir / MANIFEST, None)
        if not isinstance(manifest, dict):
            raise ConfigurationError(f"No readable {MANIFEST} in {run_dir}")
        logger.info("Resuming multi-table run %s", manifest["run_id"])
        return self._execute(run_dir, manifest)

    # -- execution --------------------------------------------------------------------
    def _execute(self, run_dir: Path, manifest: dict[str, Any]) -> JobResult:
        from app.engine import JobResult  # pylint: disable=import-outside-toplevel

        started = time.perf_counter()
        base = manifest["request"]
        specs = {s.name: s for s in parse_tables(base["schema"], base.get("generation_instructions"))}
        manifest["status"] = "running"
        for entry in manifest["tables"]:
            spec = specs[entry["name"]]
            if entry["status"] == "completed" and Path(entry.get("file") or "").exists():
                continue
            if self.engine.cancel_requested:
                return self._stop(run_dir, manifest, "cancelled", "CancelledError",
                                  f"cancelled; continue with: python -m app.main resume {manifest['run_id']}", started)
            try:
                result = self._run_table(run_dir, manifest, spec, entry, specs)
            except SchemaError as exc:
                return self._stop(run_dir, manifest, "failed", "SchemaError", f"table {spec.name!r}: {exc}", started)
            entry.update(status=result.status, job_dir=result.job_dir, error=result.error,
                         quality_score=((result.summary.get("validation") or {}).get("quality") or {}).get("score")
                         if result.summary else None)
            if not result.ok:
                self._save(run_dir, manifest)
                reason = (result.error or "").strip()[:400]
                return self._stop(run_dir, manifest, result.status, result.error_type,
                                  f"table {spec.name!r} {result.status}: {reason} Finished tables are kept; continue "
                                  f"with: python -m app.main resume {manifest['run_id']}", started)
            try:
                entry.update(self._export(run_dir, manifest, spec, Path(result.final_output), specs))
            except (MergeError, StorageError) as exc:
                entry["status"] = "failed"
                return self._stop(run_dir, manifest, "failed", type(exc).__name__,
                                  f"table {spec.name!r}: {exc}", started)
            self._save(run_dir, manifest)
            logger.info("Multi-table run %s: table %s done (%s records)", manifest["run_id"], spec.name,
                        f"{entry['records']:,}")
        manifest.update(status="completed", finished_at=utc_now_iso())
        self._save(run_dir, manifest)
        summary = self._summary(manifest, started)
        write_json_atomic(run_dir / "metadata" / "multi_table_summary.json", summary)
        return JobResult(status="completed", job_id=manifest["run_id"], job_dir=str(run_dir),
                         final_output=str(run_dir / "final"), summary=summary)

    def _stop(self, run_dir: Path, manifest: dict[str, Any], status: str, error_type: str | None, message: str,
              started: float) -> JobResult:
        from app.engine import JobResult  # pylint: disable=import-outside-toplevel

        manifest["status"] = status
        self._save(run_dir, manifest)
        logger.error("Multi-table run %s stopped: %s", manifest["run_id"], message)
        return JobResult(status=status, job_id=manifest["run_id"], job_dir=str(run_dir), final_output=None,
                         summary=self._summary(manifest, started), error=message, error_type=error_type)

    def _run_table(self, run_dir: Path, manifest: dict[str, Any], spec: TableSpec, entry: dict[str, Any],
                   specs: dict[str, TableSpec]) -> JobResult:
        tables_dir = run_dir / "tables"
        existing = find_job_dir(tables_dir, spec.name) if tables_dir.is_dir() else None
        if existing is not None and ((existing / "metadata" / "job_config.json").exists()
                                     or (existing / "split_run.json").exists()):
            logger.info("Resuming table %s", spec.name)
            return self.engine.resume(existing)
        seed = int(manifest["request"]["seed"])
        context: dict[str, Any] = {"links": {}}
        links_dir = run_dir / "links"
        if spec.per_parent is not None:
            counts = self._per_parent_counts(links_dir, spec, seed)
            context["per_parent"] = {"link": PARENT_LINK, "counts": str(counts[0]), "rows": counts[2],
                                     "max": spec.per_parent["max"],
                                     "store": str(links_dir / spec.per_parent["table"])}
            entry["records"] = counts[1]
            if counts[1] == 0:
                raise SchemaError("per_parent gives 0 rows (no parent row passes the where filter, or max is 0)")
        total = int(entry["records"])
        for link_name, link in spec.links.items():
            if link_name == PARENT_LINK:
                continue
            context["links"][link_name] = self._link_context(links_dir, spec, link_name, link, total)
        self._save(run_dir, manifest)
        base = manifest["request"]
        request = {**base, "schema": spec.raw_schema, "total_records": total, "output_format": "jsonl",
                   "schema_name": spec.name, "job_id": spec.name, "output_dir": str(tables_dir),
                   "seed": stable_seed(seed, spec.name) % 2 ** 31, "links": context, "sub_job": None,
                   "generation_instructions": "\n".join(filter(None, [base.get("generation_instructions"),
                                                                      spec.instructions])) or None}
        logger.info("Table %s: generating %s records", spec.name, f"{total:,}")
        return self.engine.run(GenerationRequest(**request))

    @staticmethod
    def _per_parent_counts(links_dir: Path, spec: TableSpec, seed: int) -> tuple[Path, int, int]:
        """Write the cumulative child counts per parent row; return the file and the child total."""
        rule = spec.per_parent or {}
        low, high, weights = rule["min"], rule["max"], rule.get("weights")
        cumulative = list(np.cumsum(weights) / sum(weights)) if weights else None
        key = text_key(f"{spec.name}:per_parent")
        starts, total = [0], 0
        for row_no, row in enumerate(iter_store(str(links_dir / rule["table"]))):
            if not row_matches(row, rule["where"]):
                count = 0
            elif cumulative is not None:
                draw = (mix64(seed, key, row_no) >> 11) / float(1 << 53)
                count = low + min(int(np.searchsorted(cumulative, draw, side="right")), high - low)
            else:
                count = low + mix64(seed, key, row_no) % (high - low + 1)
            total += count
            starts.append(total)
        path = links_dir / f"{spec.name}.counts"
        write_int64(path, starts)
        return path, total, sum(1 for a, b in zip(starts, starts[1:]) if b > a)

    @staticmethod
    def _link_context(links_dir: Path, spec: TableSpec, link_name: str, link: dict[str, Any],
                      total: int) -> dict[str, Any]:
        store = links_dir / link["table"]
        rows = max(len(Path(f"{store}.offsets").read_bytes()) // 8 - 1, 0)
        context: dict[str, Any] = {"table": link["table"], "store": str(store), "rows": rows, "mode": link["mode"],
                                   "match": list(link["match"])}
        eligible = rows
        if link["where"] or link["match"]:
            groups: dict[str, list[int]] = {}
            for row_no, row in enumerate(iter_store(str(store))):
                if row_matches(row, link["where"]):
                    key = match_key(row.get(c) for c in link["match"].values()) if link["match"] else ""
                    groups.setdefault(key, []).append(row_no)
            ordered, ranges, start = [], {}, 0
            for key, members in groups.items():
                ordered.extend(members)
                ranges[key] = (start, len(members))
                start += len(members)
            path = links_dir / f"{spec.name}__{link_name}.eligible"
            write_int64(path, ordered)
            context["eligible"] = str(path)
            if link["match"]:
                groups_file = links_dir / f"{spec.name}__{link_name}.groups.json"
                write_json_atomic(groups_file, ranges)
                context["groups"] = str(groups_file)
            eligible = len(ordered)
        context["eligible_rows"] = eligible
        if eligible == 0:
            raise SchemaError(f"link {link_name!r}: no row of {link['table']!r} passes the where filter")
        if link["mode"] == "unique" and total > eligible:
            raise SchemaError(f"link {link_name!r} is unique, but {link['table']!r} has only {eligible:,} rows to "
                              f"link {total:,} records to; lower the records or use mode random")
        if link["mode"] == "cover" and total < eligible:
            logger.warning("Table %s: link %s covers %s parent rows with only %s records; some parents get none",
                           spec.name, link_name, f"{eligible:,}", f"{total:,}")
        return context

    # -- export, key stores and integrity -------------------------------------------------
    def _export(self, run_dir: Path, manifest: dict[str, Any], spec: TableSpec, source: Path,
                specs: dict[str, TableSpec]) -> dict[str, Any]:
        fmt = manifest["output_format"]
        columns = [c for c in spec.schema.columns if c not in spec.hidden]
        target = run_dir / "final" / f"{spec.name}.{fmt}"
        store = _Writer(run_dir / "links" / spec.name, sorted(spec.needed)) if spec.needed else None
        key_hashes = array("q")
        checks = {name: (fields, array("q")) for name in spec.links if (fields := spec.link_fields(name))}
        match_pairs = {name: spec.links[name]["match"] for name in checks}

        def rows() -> Any:
            for record in iter_records(source, "jsonl"):
                if store is not None:
                    store.add(record)
                if spec.primary_key:
                    key_hashes.append(record_hash(record, spec.primary_key))
                for name, (fields, hashes) in checks.items():
                    probe = {column: record.get(child) for child, column in fields.items()}
                    probe.update({column: record.get(child) for child, column in match_pairs[name].items()})
                    hashes.append(record_hash(probe, list(probe)))
                yield record

        try:
            with atomic_writer(target, newline="" if fmt == "csv" else None) as out:
                count = write_records(out, rows(), columns, fmt)
        finally:
            if store is not None:
                store.close()
        report: dict[str, Any] = {"records": count, "file": str(target), "columns": columns}
        if spec.primary_key:
            values = np.frombuffer(key_hashes, dtype=np.int64)
            duplicates = int(len(values) - len(np.unique(values)))
            report["primary_key"] = {"columns": spec.primary_key, "duplicates": duplicates}
            if duplicates:
                raise MergeError(f"primary key {spec.primary_key} has {duplicates:,} duplicate values")
        integrity = {}
        for name, (fields, hashes) in checks.items():
            link = spec.links[name]
            columns_used = sorted({*fields.values(), *link["match"].values()})
            parent_hashes = array("q", (record_hash({c: row.get(c) for c in columns_used}, columns_used)
                                        for row in iter_store(str(run_dir / "links" / link["table"]))
                                        if row_matches(row, link["where"])))
            broken = int((~np.isin(np.frombuffer(hashes, dtype=np.int64),
                                   np.frombuffer(parent_hashes, dtype=np.int64))).sum()) if len(hashes) else 0
            integrity[name] = {"parent": link["table"], "columns": fields, "checked": len(hashes), "broken": broken}
            if broken:
                raise MergeError(f"link {name!r}: {broken:,} rows point to no matching row of {link['table']!r}")
        report["links"] = integrity
        if count != spec_count(manifest, spec.name):
            raise MergeError(f"exported {count:,} rows, expected {spec_count(manifest, spec.name):,}")
        source.unlink(missing_ok=True)  # the exported file replaces the engine's copy
        return {"status": "completed", **report}

    @staticmethod
    def _save(run_dir: Path, manifest: dict[str, Any]) -> None:
        write_json_atomic(run_dir / MANIFEST, {**manifest, "updated_at": utc_now_iso()})

    @staticmethod
    def _summary(manifest: dict[str, Any], started: float) -> dict[str, Any]:
        tables = {t["name"]: {k: t.get(k) for k in ("status", "records", "file", "quality_score", "primary_key",
                                                     "links", "error")} for t in manifest["tables"]}
        done = sum(t.get("records") or 0 for t in manifest["tables"] if t["status"] == "completed")
        scores = [t["quality_score"] for t in manifest["tables"] if t.get("quality_score") is not None]
        elapsed = time.perf_counter() - started
        return {"execution": {"multi_table": True, "tables": len(manifest["tables"]),
                              "valid_records_generated": done, "this_session_seconds": round(elapsed, 2)},
                "validation": {"quality": {"score": min(scores)} if scores else None}, "tables": tables}


def spec_count(manifest: dict[str, Any], name: str) -> int:
    """Planned rows of table ``name``."""
    return int(next(t for t in manifest["tables"] if t["name"] == name)["records"])
